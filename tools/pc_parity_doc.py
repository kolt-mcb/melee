#!/usr/bin/env python3
"""Render the console-parity grid as a document.

Reads tests/pc/lockstep_baseline.json -- the record tools/pc_lockstep_matrix.py
keeps, one entry per cell, "<char>,<char>,<stage>": frames-identical-to-the-console
-- and writes docs/parity-matrix.md: a character-by-stage grid of how far each
mirror match stays bit-identical to Dolphin.

The number in a cell is frames, not a percentage of anything. A cell that parts at
frame 300 is not "50% right": the simulation is exact until it is not, and after the
first differing frame the two runs are simply different matches. Quoting a
percentage of *frames* would flatter a cell that drifts early and then happens to
agree again. So the grid carries frames, and the summary counts cells that clear
each bar.

    tools/pc_parity_doc.py [--baseline F] [--out F]
"""
import argparse
import collections
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The bars the parity plan ratchets through. Only those at or below the sweep's
# own frame budget mean anything: a cell cannot clear a bar the run never reached.
BARS = [("7200", 7200), ("2400", 2400), ("600", 600), ("60", 60)]


def enum_names(path, prefix):
    """Pull `prefix`-named enumerators and their values out of a header."""
    src = open(os.path.join(ROOT, path)).read()
    out, val = {}, 0
    for line in src.split("\n"):
        line = re.sub(r"/\*.*?\*/", "", line)
        line = line.split("//")[0].strip().rstrip(",")
        m = re.match(r"^(" + prefix + r"\w+)\s*(?:=\s*(-?\w+))?$", line)
        if not m:
            continue
        if m.group(2):
            try:
                val = int(m.group(2), 0)
            except ValueError:
                pass
        out[val] = m.group(1)[len(prefix):]
        val += 1
    return out


def stage_labels(path):
    """Stage enumerators, preferring the trailing comment as the real name."""
    src = open(os.path.join(ROOT, path)).read()
    out, val = {}, 0
    for line in src.split("\n"):
        note = ""
        cm = re.search(r"//\s*(.+?)\s*$", line)
        if cm:
            note = cm.group(1)
        body = re.sub(r"/\*.*?\*/", "", line).split("//")[0].strip().rstrip(",")
        m = re.match(r"^(Gr_Kind_\w+)\s*(?:=\s*(-?\w+))?$", body)
        if not m:
            continue
        if m.group(2):
            try:
                val = int(m.group(2), 0)
            except ValueError:
                pass
        out[val] = note or m.group(1)[len("Gr_Kind_"):]
        val += 1
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--baseline", default="tests/pc/lockstep_baseline.json")
    ap.add_argument("--out", default="docs/parity-matrix.md")
    a = ap.parse_args()

    bpath = os.path.join(ROOT, a.baseline)
    data = json.load(open(bpath))
    mtime = __import__("datetime").date.fromtimestamp(os.path.getmtime(bpath))
    chars = enum_names("src/melee/ft/forward.h", "Ft_Kind_")
    stages = stage_labels("src/melee/gr/forward.h")

    cells = {}
    for key, frames in data.items():
        parts = key.split(",")
        if len(parts) != 3:
            continue
        c0, c1, st = (int(p) for p in parts)
        if c0 != c1:
            continue  # mirror grid only; the rotate grid is a separate sweep
        cells[(c0, st)] = frames

    used_chars = sorted({c for c, _ in cells})
    used_stages = sorted({s for _, s in cells})

    budget = max(cells.values()) if cells else 0

    def cell_mark(n):
        if n is None:
            return "   ."
        if n >= budget:
            return "  ok"          # never parted inside the measured window
        if n >= budget // 2:
            return " %3d" % n
        return "%4d" % n

    lines = []
    w = lines.append
    w("# Console parity: character x stage")
    w("")
    w("How far each mirror match stays **bit-identical to Dolphin**, in frames,")
    w("from `%s`." % a.baseline)
    w("")
    w("Generated by `tools/pc_parity_doc.py`. Do not hand-edit.")
    w("")
    w("Baseline recorded %s." % mtime)
    w("")
    w("> **Check the date before quoting these numbers.** The lockstep harness")
    w("> has been wrong about this grid before: it sampled the console at the")
    w("> GPU's frame boundary rather than after the simulation, reseeded the")
    w("> second fighter at the wrong moment, and freed JIT code it was")
    w("> executing. All three made cells look like they diverged when they had")
    w("> not. A baseline taken before those fixes reads pessimistically, and")
    w("> re-running the sweep is the only way to know which it is.")
    w("")
    w("Read the number as frames, not a score. The simulation is exact until it")
    w("is not; after the first differing frame the two runs are different")
    w("matches, so a cell that parts at 300 is not \"half right\".")
    w("")
    w("    ok    never parted inside the measured window")
    w("    <n>   the frame it first differs on")
    w("    .     not measured")
    w("")

    total = len(cells)
    counts = collections.OrderedDict()
    for name, bar in BARS:
        if bar <= budget:
            counts[name] = sum(1 for n in cells.values() if n >= bar)
    w("## Summary")
    w("")
    w("**This sweep ran %d frames per cell**, so that number is a ceiling on the"
      % budget)
    w("measurement, not on the port. A cell showing `ok` never parted inside the")
    w("window; it is not known to be exact beyond it. Bars above %d are not"
      % budget)
    w("reported -- no cell could have cleared them.")
    w("")
    w("| bar | cells | share |")
    w("| --- | ---: | ---: |")
    for name, bar in BARS:
        if bar > budget:
            continue
        label = ("clean for the whole %s-frame window" % name) if bar == budget \
            else ("identical through %s frames" % name)
        w("| %s | %d of %d | %.0f%% |"
          % (label, counts[name], total,
             100.0 * counts[name] / total if total else 0))
    w("")
    w("The plan's definition of done is every cell clean at 7200 frames, which")
    w("needs the sweep's budget raised before it can even be asked.")
    w("")

    # per-character rollup, worst first: where the work is
    w("## By character")
    w("")
    w("| character | cells | best | median | clean |")
    w("| --- | ---: | ---: | ---: | ---: |")
    per = collections.defaultdict(list)
    for (c, s), n in cells.items():
        per[c].append(n)
    for c in sorted(per, key=lambda c: (sum(1 for n in per[c] if n >= budget), max(per[c]))):
        v = sorted(per[c])
        med = v[len(v) // 2]
        w("| %s | %d | %d | %d | %d |"
          % (chars.get(c, "?%d" % c), len(v), max(v), med,
             sum(1 for n in v if n >= budget)))
    w("")

    w("## By stage")
    w("")
    w("| stage | cells | best | median | clean |")
    w("| --- | ---: | ---: | ---: | ---: |")
    pers = collections.defaultdict(list)
    for (c, s), n in cells.items():
        pers[s].append(n)
    for s in sorted(pers, key=lambda s: (sum(1 for n in pers[s] if n >= budget), max(pers[s]))):
        v = sorted(pers[s])
        med = v[len(v) // 2]
        w("| %s | %d | %d | %d | %d |"
          % (stages.get(s, "?%d" % s), len(v), max(v), med,
             sum(1 for n in v if n >= budget)))
    w("")

    w("## The grid")
    w("")
    w("Rows are characters, columns are stages, in the same order as the")
    w("per-stage table above.")
    w("")
    w("```")
    hdr = "%-12s" % ""
    for i, s in enumerate(used_stages):
        hdr += "%-5s" % ("s%d" % s)
    w(hdr)
    for c in used_chars:
        row = "%-12s" % chars.get(c, "?%d" % c)[:11]
        for s in used_stages:
            row += "%-5s" % cell_mark(cells.get((c, s)))
        w(row)
    w("")
    w("stage numbers:")
    for s in used_stages:
        w("  s%-3d %s" % (s, stages.get(s, "?")))
    w("```")
    w("")

    outp = os.path.join(ROOT, a.out)
    open(outp, "w").write("\n".join(lines) + "\n")
    print("wrote %s: %d cells, %d characters, %d stages"
          % (a.out, total, len(used_chars), len(used_stages)))
    for name, bar in BARS:
        if bar > budget:
            continue
        print("  through %5s frames: %3d (%.0f%%)%s"
              % (name, counts[name],
                 100.0 * counts[name] / total if total else 0,
                 "   <- the whole window" if bar == budget else ""))


if __name__ == "__main__":
    sys.exit(main())
